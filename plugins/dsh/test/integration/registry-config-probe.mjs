import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const entry = process.env.DSH_PROBE_URL;
if (!entry) throw new Error('Set isolated component fixture URL');
const browser = await chromium.launch({ headless: true, executablePath: process.env.DSH_PROBE_CHROMIUM });
const page = await browser.newPage({ viewport: { width: 1100, height: 900 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(entry);
  const settings = page.getByRole('form', { name: 'SkillHub 配置' });
  const selector = page.getByRole('region', { name: '快速切换' }).getByRole('combobox', { name: '技能来源' });
  if (process.env.DSH_PROBE_SCREENSHOT) await page.screenshot({ path: `${process.env.DSH_PROBE_SCREENSHOT}-desktop.png`, fullPage: true });
  await settings.getByRole('textbox', { name: '来源 1 名称', exact: true }).fill('A 草稿');
  await selector.click();
  await page.getByRole('option', { name: '来源 B', exact: true }).click();
  await page.waitForFunction(() => window.registryFixture.state().value.registryUrl === 'https://b.example');
  await settings.getByRole('button', { name: '保存配置', exact: true }).click();
  await settings.getByText('配置未保存，可能已被其他页面修改。请重置修改后再试。').waitFor();
  assert.equal(await page.evaluate(() => window.registryFixture.state().value.savedRegistries[0].name), '来源 A');
  await settings.getByRole('button', { name: '重置修改', exact: true }).click();
  await settings.getByRole('textbox', { name: '来源 2 地址', exact: true }).fill('https://new-b.example');
  await settings.getByRole('button', { name: '保存配置', exact: true }).click();
  await page.waitForFunction(() => window.registryFixture.state().value.registryUrl === 'https://new-b.example');
  assert.equal(await page.evaluate(() => window.registryFixture.state().value.savedRegistries[1].url), 'https://new-b.example');
  await settings.getByRole('button', { name: '移除来源 2', exact: true }).click();
  await settings.getByRole('button', { name: '保存配置', exact: true }).click();
  await page.waitForFunction(() => window.registryFixture.state().value.registryUrl === '');
  await settings.getByRole('button', { name: '添加来源', exact: true }).click();
  await settings.getByRole('textbox', { name: '来源 2 名称', exact: true }).fill('重复');
  await settings.getByRole('textbox', { name: '来源 2 地址', exact: true }).fill('https://a.example/');
  await settings.getByRole('button', { name: '保存配置', exact: true }).click();
  await settings.getByText('此来源地址已存在，请保留一个条目。').waitFor();
  await settings.getByRole('button', { name: '重置修改', exact: true }).click();
  await page.evaluate(() => window.registryFixture.readonly());
  await page.waitForFunction(() => document.querySelector('[aria-label="技能来源"]').disabled);
  assert.equal(await settings.getByRole('button', { name: '添加来源', exact: true }).isDisabled(), true);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  if (process.env.DSH_PROBE_SCREENSHOT) await page.screenshot({ path: `${process.env.DSH_PROBE_SCREENSHOT}-mobile.png`, fullPage: true });
  await page.evaluate(() => window.registryFixture.unavailable());
  await selector.getByText('来源配置不可用').waitFor();
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, cases: ['shared selection', 'stale draft CAS refusal', 'active URL atomic edit', 'active removal disconnect', 'duplicate refusal', 'readonly', 'narrow layout', 'missing config service'] }));
} finally { await browser.close(); }
